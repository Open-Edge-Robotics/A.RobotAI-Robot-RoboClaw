"""마지막으로 파악한 로봇 위치(마지막 위치)를 YAML 파일 1개로 유지한다.

두 가지 용도로 쓴다.

1. **Nav2 기동 시 AMCL 초기 위치.** former 의 nav2 기동 스크립트
   (`former/<robot>/run_former_env.sh nav2`)가 이 파일을 읽어 `nav2_params.yaml` 의
   `amcl.initial_pose` 를 덮어쓴다. 그래서 전원을 다시 켜도 위치를 다시 지정할 필요가
   없다. 스크립트가 bash 로 읽으므로 **평면 `key: value` 형식만** 쓴다.
2. **"마지막 위치를 초기 위치로" 요청.** 네비게이션만 재기동되어 AMCL 이 초기 위치를
   잃었을 때 `set_initial_pose(target_name="마지막 위치")` 가 이 값을 쓴다.

파일은 에이전트 메모리 디렉터리(`memory_path` 의 상위, 컨테이너 `/ros2_ws/memory`,
호스트 기본 `<repo>/agent_workspace/memory`)에 둔다. rclaw CLI 가 이미 rw 로 마운트하는
경로라 새 마운트가 필요 없고, 컨테이너 재시작 후에도 남는다.

예전에는 RAG 레코드(`type="last_pose"`)로 저장했다. 이미 남아 있는 레코드가 장소 지식으로
오인되지 않도록 `semantic._FWD_SKIP_TYPES` 와 `rag._NON_LOCATION_TYPES` 의 제외 항목은
유지한다(`LAST_POSE_TYPE`).
"""

from __future__ import annotations

import json
import logging
import math
import os
import tempfile
from datetime import datetime
from typing import Any

logger = logging.getLogger(__name__)

#: 예전 RAG 레코드 타입(레거시 레코드 제외용으로만 남긴다).
LAST_POSE_TYPE = "last_pose"
#: 메모리 디렉터리 안의 파일 이름. nav2 기동 스크립트도 같은 이름을 찾는다.
LAST_POSE_FILENAME = "last_pose.yaml"
LAST_POSE_FILE_VERSION = 1
#: 사용자가 "마지막 위치"를 가리킬 때 쓰는 표현(정규화 후 비교: 공백 제거 + 소문자).
LAST_POSE_DISPLAY_NAME = "마지막 위치"
LAST_POSE_ALIASES: frozenset[str] = frozenset(
    {
        "마지막위치",
        "마지막장소",
        "마지막지점",
        "마지막포즈",
        "마지막자리",
        "마지막으로있던곳",
        "마지막으로있던위치",
        "직전위치",
        "직전장소",
        "방금전위치",
        "lastpose",
        "lastposition",
    }
)


def is_last_pose_request(name: str) -> bool:
    """장소명 자리에 '마지막 위치'류 표현이 왔는지 판정한다."""
    normalized = "".join(str(name or "").split()).lower()
    return normalized in LAST_POSE_ALIASES


def resolve_last_pose_path(memory_path: str | None) -> str:
    """에이전트 `memory_path`(예: `/ros2_ws/memory/memory.json`)에서 파일 경로를 만든다.

    memory_path 가 비어 있으면 빈 문자열(파일 저장 비활성)을 돌려준다.
    """
    raw = str(memory_path or "").strip()
    if not raw:
        return ""
    return os.path.join(os.path.dirname(os.path.abspath(raw)), LAST_POSE_FILENAME)


def _finite(value: Any) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def format_last_pose_yaml(
    *,
    x: float,
    y: float,
    yaw: float,
    frame: str = "map",
    map_name: str = "",
    near_place: str = "",
    updated_at: str = "",
) -> str:
    """파일 본문을 만든다(순수 함수).

    문자열 값은 JSON 따옴표로 감싼다. YAML 의 큰따옴표 문자열과 호환되고, bash 쪽은
    앞뒤 따옴표만 벗기면 된다.
    """
    return (
        "# RoboClaw last known robot pose (map frame). Auto-generated by robo_claw_agent.\n"
        "# Read by former/<robot>/run_former_env.sh to seed the AMCL initial pose.\n"
        f"version: {LAST_POSE_FILE_VERSION}\n"
        f"frame: {json.dumps(str(frame or 'map'))}\n"
        f"map: {json.dumps(str(map_name or ''), ensure_ascii=False)}\n"
        f"x: {float(x):.3f}\n"
        f"y: {float(y):.3f}\n"
        f"yaw: {float(yaw):.4f}\n"
        f"near_place: {json.dumps(str(near_place or ''), ensure_ascii=False)}\n"
        f"updated_at: {json.dumps(str(updated_at or ''))}\n"
    )


def _parse_flat_yaml(text: str) -> dict[str, str]:
    """`key: value` 평면 형식만 읽는다(중첩·목록 미지원). 큰따옴표 값은 JSON 으로 푼다.

    외부 YAML 라이브러리 의존을 두지 않고, bash 쪽 파서와 같은 규칙을 쓰기 위함이다.
    """
    values: dict[str, str] = {}
    for raw_line in str(text or "").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith('"'):
            try:
                decoded = json.loads(value)
            except json.JSONDecodeError:
                continue
            value = str(decoded)
        values[key.strip()] = value
    return values


def parse_last_pose_yaml(text: str) -> dict[str, Any] | None:
    """파일 본문을 pose dict 로 해석한다(순수 함수). 형식이 틀리면 None."""
    data = _parse_flat_yaml(text)
    x = _finite(data.get("x"))
    y = _finite(data.get("y"))
    if x is None or y is None:
        return None
    yaw = _finite(data.get("yaw"))
    return {
        "x": x,
        "y": y,
        "yaw": yaw if yaw is not None else 0.0,
        "frame": str(data.get("frame") or "map"),
        "map": str(data.get("map") or ""),
        "near_place": str(data.get("near_place") or ""),
        "updated_at": str(data.get("updated_at") or ""),
    }


def read_last_pose_file(path: str) -> dict[str, Any] | None:
    """저장된 마지막 위치를 읽는다. 파일이 없거나 형식이 틀리면 None."""
    if not path:
        return None
    try:
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
    except FileNotFoundError:
        return None
    except OSError as exc:
        logger.warning("last_pose_read_failed path=%s err=%s", path, exc)
        return None
    pose = parse_last_pose_yaml(text)
    if pose is None:
        logger.warning("last_pose_parse_failed path=%s", path)
    return pose


def write_last_pose_file(
    path: str,
    *,
    x: float,
    y: float,
    yaw: float,
    frame: str = "map",
    map_name: str = "",
    near_place: str = "",
    updated_at: str | None = None,
) -> bool:
    """마지막 위치를 원자적으로 저장한다(임시 파일 → fsync → rename).

    쓰는 도중 전원이 꺼져도 이전 파일이 그대로 남는다. 실패해도 로봇 동작을 막지
    않도록 예외 대신 False 를 돌려준다.
    """
    if not path:
        return False
    if any(_finite(v) is None for v in (x, y, yaw)):
        return False
    body = format_last_pose_yaml(
        x=float(x),
        y=float(y),
        yaw=float(yaw),
        frame=frame,
        map_name=map_name,
        near_place=near_place,
        updated_at=updated_at or datetime.now().astimezone().isoformat(timespec="seconds"),
    )
    directory = os.path.dirname(os.path.abspath(path))
    tmp_path = ""
    try:
        os.makedirs(directory, exist_ok=True)
        fd, tmp_path = tempfile.mkstemp(prefix=".last_pose.", suffix=".tmp", dir=directory)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(body)
            handle.flush()
            os.fsync(handle.fileno())
        # nav 기동 스크립트(호스트 일반 사용자)가 읽을 수 있게 0644 로 둔다.
        os.chmod(tmp_path, 0o644)
        os.replace(tmp_path, path)
        tmp_path = ""
        return True
    except OSError as exc:
        logger.error("last_pose_write_failed path=%s err=%s", path, exc)
        return False
    finally:
        if tmp_path:
            try:
                os.unlink(tmp_path)
            except OSError:
                pass
